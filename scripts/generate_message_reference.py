"""Generate the message reference from :mod:`pitloom.messages`.

The catalogue is the source of truth. This script rewrites only the text
between ``<!-- BEGIN GENERATED: pitloom.messages -->`` and
``<!-- END GENERATED -->`` in each target file with a Markdown table, one
row per catalogued message, sorted by code. The output has LF line endings
and no dates, so it is byte-for-byte reproducible.

    python scripts/generate_message_reference.py            # update (--write)
    python scripts/generate_message_reference.py --check   # exit 1 if stale

``--check`` prints a unified diff of each stale target to stderr and exits 1.
Exit status 2: a target lacks the markers (or has them twice).
"""

from __future__ import annotations

import argparse
import difflib
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Final

from pitloom.messages import MESSAGES, Message

ROOT: Final = Path(__file__).resolve().parents[1]

#: The files holding a generated block.
TARGETS: Final = (
    ROOT / "docs" / "messages.md",
    ROOT / "skills" / "sbom-generate" / "references" / "known-limitations.md",
)

BEGIN: Final = "<!-- BEGIN GENERATED: pitloom.messages -->"
END: Final = "<!-- END GENERATED -->"

_LEVEL_ORDER: Final = ("ERROR", "WARNING", "INFO")
_HEADER: Final = (
    "| Code | Level | Printed as | Meaning | What Pitloom did | What to tell the user |"
)
_NOTE: Final = (
    "<!-- Generated by scripts/generate_message_reference.py; "
    "do not edit. -->\n"
    "A line reads `LEVEL: text [code]`; `%s` in a text stands for a value."
)


def cell(text: str) -> str:
    """*text* as one table cell: ``|`` escaped, a line break flattened."""
    return " ".join(text.split()).replace("|", "\\|")


def _row(message: Message) -> str:
    """The table row for *message*."""
    levels = ", ".join(lv for lv in _LEVEL_ORDER if lv in message.levels)
    printed = " or ".join(f"`{cell(p)}`" for p in message.patterns)
    cells = (
        f"`{message.code}`",
        levels,
        printed,
        cell(message.summary),
        cell(message.did),
        cell(message.advice),
    )
    return "| " + " | ".join(cells) + " |"


def render() -> str:
    """The generated block's body: the note and the table, LF, no trailing
    newline."""
    rows = [_row(MESSAGES[code]) for code in sorted(MESSAGES)]
    divider = "| " + " | ".join(["---"] * 6) + " |"
    return "\n".join([_NOTE, "", _HEADER, divider, *rows])


def replace_block(text: str, body: str) -> str:
    """*text* with what lies between the markers replaced by *body*.

    Raises:
        ValueError: The markers are missing, repeated or out of order.
    """
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError(f"needs exactly one {BEGIN!r} and one {END!r}")
    head, _, rest = text.partition(BEGIN)
    _, found, tail = rest.partition(END)
    if not found or END in head:
        raise ValueError(f"{END!r} comes before {BEGIN!r}")
    return f"{head}{BEGIN}\n{body}\n{END}{tail}"


def _updated(path: Path, body: str) -> tuple[bytes, bytes]:
    """The bytes of *path* now, and as they should be."""
    current = path.read_bytes()
    wanted = replace_block(current.decode("utf-8"), body).encode("utf-8")
    return current, wanted


def _diff(path: Path, current: bytes, wanted: bytes) -> str:
    """A unified diff from *current* to *wanted*, for *path*."""
    name = path.relative_to(ROOT).as_posix()
    return "".join(
        difflib.unified_diff(
            current.decode("utf-8").splitlines(keepends=True),
            wanted.decode("utf-8").splitlines(keepends=True),
            f"a/{name}",
            f"b/{name}",
        )
    )


def run(targets: Sequence[Path], *, check: bool) -> int:
    """Update (or with *check*, only compare) *targets*; the exit status."""
    body = render()
    status = 0
    for path in targets:
        name = path.relative_to(ROOT).as_posix()
        try:
            current, wanted = _updated(path, body)
        except (OSError, UnicodeDecodeError, ValueError) as exc:
            print(f"ERROR: {name}: {exc}", file=sys.stderr)
            return 2
        if current == wanted:
            continue
        if check:
            print(_diff(path, current, wanted), end="", file=sys.stderr)
            print(
                f"ERROR: {name}: stale; run "
                "'python scripts/generate_message_reference.py'",
                file=sys.stderr,
            )
            status = 1
        else:
            path.write_bytes(wanted)
            print(f"INFO: {name}: updated", file=sys.stderr)
    return status


def main(argv: Sequence[str] | None = None) -> int:
    """The command line."""
    parser = argparse.ArgumentParser(
        description=(__doc__ or "").split("\n\n", maxsplit=1)[0]
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check", action="store_true", help="exit 1 with a diff if a target is stale"
    )
    mode.add_argument(
        "--write", action="store_true", help="update the targets (the default)"
    )
    args = parser.parse_args(argv)
    return run(TARGETS, check=args.check)


if __name__ == "__main__":
    sys.exit(main())
